"""Figures for Article 11, computed from the CBDT AY 2023-24 tables.

Reads the CSVs written by cbdt_tables.py and writes data/ay2023-24-summary.md,
which lists every number the article quotes and how it was derived.

Thresholds inside a range (for example "the top 2% starts at about Rs 44 lakh")
assume people are spread evenly across that range: an estimate, marked as such.

Usage:
    python3 -I research/scripts/analyse_ay2023_24.py
"""

from __future__ import annotations

import csv
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "data"
LAKH, CRORE = 100_000, 10_000_000

# The article's brackets; the CBDT ranges have no break at Rs 12 lakh or Rs 2 crore.
BRACKETS = [
    ("Up to ₹10 lakh", 0, 10 * LAKH),
    ("₹10–15 lakh", 10 * LAKH, 15 * LAKH),
    ("₹15–25 lakh", 15 * LAKH, 25 * LAKH),
    ("₹25–50 lakh", 25 * LAKH, 50 * LAKH),
    ("₹50 lakh–₹1 crore", 50 * LAKH, CRORE),
    ("₹1–5 crore", CRORE, 5 * CRORE),
    ("Above ₹5 crore", 5 * CRORE, None),
]


def load(name: str) -> list[dict]:
    with (DATA / f"cbdt-ay2023-24-{name}.csv").open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        r["lower"] = int(r["lower_inr"]) if r["lower_inr"] else None
        r["upper"] = int(r["upper_inr"]) if r["upper_inr"] else None
        r["n"] = int(r["returns"])
        r["sum"] = float(r["sum_crore"]) if r["sum_crore"] else 0.0
    return rows


def positive(rows: list[dict]) -> list[dict]:
    """Rows above zero (drops '<0' and '=0')."""
    return [r for r in rows if r["upper"] is None or r["upper"] > 0]


def in_bracket(r: dict, lo: int, hi: int | None) -> bool:
    return r["lower"] >= lo and (hi is None or (r["upper"] is not None and r["upper"] <= hi))


def threshold(rows: list[dict], share: float) -> tuple[float, dict]:
    """Income at which the top `share` of rows begins (linear within its range)."""
    need = share * sum(r["n"] for r in rows)
    above = 0
    for r in sorted(rows, key=lambda r: r["lower"], reverse=True):
        if above + r["n"] >= need:
            if r["upper"] is None:
                return float(r["lower"]), r
            fraction = (need - above) / r["n"]
            return r["upper"] - fraction * (r["upper"] - r["lower"]), r
        above += r["n"]
    raise ValueError("share out of range")


def bracket_table(rows: list[dict], total_n: int, what: str, nil_row: bool = True) -> list[str]:
    pos = positive(rows)
    total_sum = sum(r["sum"] for r in pos)
    out = [f"| Range | Returns | % of returns | Cumulative % | % of {what} |", "|---|---|---|---|---|"]
    zero = total_n - sum(r["n"] for r in pos)
    cumulative = zero
    if nil_row:
        out.append(f"| Nil or negative | {zero:,} | {100 * zero / total_n:.2f}% "
                   f"| {100 * cumulative / total_n:.2f}% | 0% |")
    for label, lo, hi in BRACKETS:
        n = sum(r["n"] for r in pos if in_bracket(r, lo, hi))
        s = sum(r["sum"] for r in pos if in_bracket(r, lo, hi))
        cumulative += n
        out.append(f"| {label} | {n:,} | {100 * n / total_n:.2f}% | {100 * cumulative / total_n:.2f}% "
                   f"| {100 * s / total_sum:.2f}% |")
    return out


def share_from(rows: list[dict], cut: int) -> tuple[int, float, float, float]:
    pos = positive(rows)
    n_all, s_all = sum(r["n"] for r in pos), sum(r["sum"] for r in pos)
    n = sum(r["n"] for r in pos if r["lower"] >= cut)
    s = sum(r["sum"] for r in pos if r["lower"] >= cut)
    return n, 100 * n / n_all, s, 100 * s / s_all


def main() -> None:
    salary, returned, tax = load("individual-salary-income"), load("individual-returned-income"), load(
        "individual-tax-payable")
    total = sum(r["n"] for r in salary)
    lines = ["# AY 2023-24: figures used in Article 11", "",
             "Source: CBDT, *Income Tax Return Statistics, Assessment Year 2023-24* (Version 1.0), "
             "tables 2.2, 2.10 and 2.11 (individuals). Generated by `scripts/analyse_ay2023_24.py`; "
             "do not edit by hand.", "",
             f"Individual returns: {total:,}.", ""]

    # Salary (table 2.2)
    paid = positive(salary)
    salaried = sum(r["n"] for r in paid)
    total_salary = sum(r["sum"] for r in paid)
    lines += ["## Salary income (table 2.2)", "",
              f"Returns reporting salary income: {salaried:,} ({100 * salaried / total:.1f}% of individual "
              f"returns); total salary ₹{total_salary / 1e5:,.2f} lakh crore.", "",
              "| Group of salaried filers | People | Salary at which the group starts (estimate) | Range it falls in |",
              "|---|---|---|---|"]
    for share in (0.10, 0.05, 0.02, 0.01):
        value, r = threshold(paid, share)
        lines.append(f"| Top {share:.0%} | {share * salaried:,.0f} | ₹{value / LAKH:.1f} lakh | {r['range']} |")
    lines += ["", "| Salary of at least | People | % of salaried filers | % of all salary |", "|---|---|---|---|"]
    for cut in (25 * LAKH, 50 * LAKH, CRORE):
        n, pn, _, ps = share_from(salary, cut)
        lines.append(f"| ₹{cut / LAKH:,.0f} lakh | {n:,} | {pn:.2f}% | {ps:.1f}% |")
    lines += ["", "Brackets (salaried filers only; shares of salaried filers and of all salary):", ""]
    lines += bracket_table(paid, salaried, "all salary", nil_row=False)

    # Returned income (table 2.10)
    lines += ["", "## Returned income (table 2.10)", ""] + bracket_table(returned, total, "all returned income")
    for cut in (25 * LAKH, 50 * LAKH, CRORE):
        n, pn, _, ps = share_from(returned, cut)
        lines.append(f"\nReturned income of at least ₹{cut / LAKH:,.0f} lakh: {n:,} returns "
                     f"({pn:.2f}% of returns with income) reporting {ps:.1f}% of returned income.")

    # Tax payable (table 2.11)
    payers = positive(tax)
    n_payers, tax_total = sum(r["n"] for r in payers), sum(r["sum"] for r in payers)
    zero = total - n_payers
    lines += ["", "## Tax payable (table 2.11)", "",
              f"Returns with zero tax payable: {zero:,} ({100 * zero / total:.1f}%). "
              f"Returns with tax payable: {n_payers:,} ({100 * n_payers / total:.1f}%), "
              f"total tax payable ₹{tax_total:,.0f} crore.", "",
              "| Tax payable of at least | Returns | % of all individual returns | % of all tax payable |",
              "|---|---|---|---|"]
    for cut in (int(1.5 * LAKH), 5 * LAKH, 10 * LAKH, 50 * LAKH, CRORE):
        n, _, s, ps = share_from(tax, cut)
        lines.append(f"| ₹{cut / LAKH:g} lakh | {n:,} | {100 * n / total:.2f}% | {ps:.1f}% |")
    low = [r for r in payers if r["upper"] == int(1.5 * LAKH)][0]
    lines.append(f"\nTax payable up to ₹1.5 lakh: {low['n']:,} returns ({100 * low['n'] / total:.1f}% of "
                 f"returns) paying {100 * low['sum'] / tax_total:.1f}% of all tax payable.")

    out = DATA / "ay2023-24-summary.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(out.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
